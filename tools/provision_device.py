"""Register one ESP32 with AWS IoT and write its firmware secrets file.

    python tools/provision_device.py home01-livingroom

Creates the thing, a certificate with its private key, and attaches the device
policy created by the CDK stack. The certificate files and the generated
firmware/include/secrets.h contain a private key: both locations are in
.gitignore and must never be committed.

Uses the AWS credentials already configured on this machine.
"""

from __future__ import annotations

import argparse
import re
import urllib.request
from pathlib import Path

import boto3

ROOT = Path(__file__).resolve().parent.parent
ROOT_CA_URL = "https://www.amazontrust.com/repository/AmazonRootCA1.pem"
THING_NAME = re.compile(r"^[a-z0-9]+-[a-z0-9]+$")

SECRETS_TEMPLATE = """// Generated by tools/provision_device.py.
// Contains a private key: do not commit.
#pragma once

#define WIFI_SSID "CHANGE_ME"
#define WIFI_PASSWORD "CHANGE_ME"

#define THING_NAME "{thing}"
#define AWS_IOT_ENDPOINT "{endpoint}"

static const char AWS_ROOT_CA[] PROGMEM = R"PEM(
{root_ca})PEM";

static const char DEVICE_CERTIFICATE[] PROGMEM = R"PEM(
{certificate})PEM";

static const char DEVICE_PRIVATE_KEY[] PROGMEM = R"PEM(
{private_key})PEM";
"""


def provision(thing: str, policy: str, iot, root_ca: str, out_dir: Path) -> Path:
    if not THING_NAME.match(thing):
        raise SystemExit("The thing name must look like '<house>-<room>', e.g. home01-livingroom")

    iot.create_thing(thingName=thing)
    keys = iot.create_keys_and_certificate(setAsActive=True)
    iot.attach_policy(policyName=policy, target=keys["certificateArn"])
    iot.attach_thing_principal(thingName=thing, principal=keys["certificateArn"])
    endpoint = iot.describe_endpoint(endpointType="iot:Data-ATS")["endpointAddress"]

    cert_dir = out_dir / "certs" / thing
    cert_dir.mkdir(parents=True, exist_ok=True)
    (cert_dir / "certificate.pem").write_text(keys["certificatePem"])
    (cert_dir / "private.key").write_text(keys["keyPair"]["PrivateKey"])

    secrets = out_dir / "firmware" / "include" / "secrets.h"
    secrets.parent.mkdir(parents=True, exist_ok=True)
    secrets.write_text(
        SECRETS_TEMPLATE.format(
            thing=thing,
            endpoint=endpoint,
            root_ca=root_ca,
            certificate=keys["certificatePem"],
            private_key=keys["keyPair"]["PrivateKey"],
        )
    )
    return secrets


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("thing", help="thing name, '<house>-<room>'")
    parser.add_argument("--policy", default="SmartHomeDevice")
    args = parser.parse_args()

    with urllib.request.urlopen(ROOT_CA_URL, timeout=30) as response:
        root_ca = response.read().decode()
    secrets = provision(args.thing, args.policy, boto3.client("iot"), root_ca, ROOT)
    print(f"Registered {args.thing}.")
    print(f"Set WIFI_SSID and WIFI_PASSWORD in {secrets.relative_to(ROOT)}, then flash the board.")


if __name__ == "__main__":
    main()
